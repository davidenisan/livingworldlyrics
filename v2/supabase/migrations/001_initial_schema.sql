-- Living Word Lyrics v2
-- Apply in the Supabase SQL Editor, or through the Supabase CLI.

create table if not exists public.albums (
  id bigint generated by default as identity primary key,
  title text not null,
  year integer,
  description text,
  cover_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.songs (
  id bigint generated by default as identity primary key,
  album_id bigint not null references public.albums(id) on delete cascade,
  track_number integer,
  title text not null,
  lyrics text,
  youtube_url text,
  lwm_url text,
  songwriters text,
  created_at timestamptz not null default now()
);

create index if not exists songs_album_track_idx on public.songs (album_id, track_number, title);
create index if not exists songs_title_idx on public.songs (title);

-- A deliberately small allow-list: regular visitors can read the library,
-- while only explicitly approved Supabase Auth users can edit it.
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.albums enable row level security;
alter table public.songs enable row level security;
alter table public.admin_users enable row level security;

create or replace function public.is_lyrics_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_users where user_id = auth.uid()
  );
$$;

revoke all on function public.is_lyrics_admin() from public;
grant execute on function public.is_lyrics_admin() to anon, authenticated;

create policy "Public can read albums"
on public.albums for select to anon, authenticated using (true);

create policy "Admins can manage albums"
on public.albums for all to authenticated
using (public.is_lyrics_admin())
with check (public.is_lyrics_admin());

create policy "Public can read songs"
on public.songs for select to anon, authenticated using (true);

create policy "Admins can manage songs"
on public.songs for all to authenticated
using (public.is_lyrics_admin())
with check (public.is_lyrics_admin());

create policy "Admins can read admin allow-list"
on public.admin_users for select to authenticated
using (public.is_lyrics_admin());

-- The one-time importer retains existing numeric IDs. This safely advances
-- identity sequences afterwards so future creates cannot collide.
create or replace function public.sync_lyrics_identity_sequences()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  perform setval(pg_get_serial_sequence('public.albums', 'id'), coalesce((select max(id) from public.albums), 1), true);
  perform setval(pg_get_serial_sequence('public.songs', 'id'), coalesce((select max(id) from public.songs), 1), true);
end;
$$;

revoke all on function public.sync_lyrics_identity_sequences() from public;
